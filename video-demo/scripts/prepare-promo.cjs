// Snapshot the website's existing cards and assets; no changes to the website.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const out = path.resolve(__dirname, '../public/promo');
const siteCopy = require(path.join(root, 'site-copy.js'));
const englishCopy = {...siteCopy.en,
  'product.timeSeconds': 'Just now', 'product.timeMinutes': '4 min ago',
  'product.timeHours': '2 hr ago', 'product.timeHoursLong': '6 hr ago', 'product.timeTenHours': '10 hr ago',
};
fs.mkdirSync(out, {recursive: true});
const html = fs.readFileSync(path.join(root, 'src/page.html'), 'utf8');
const makeCards = copy => [...html.matchAll(/<article class="vp-clip-card[\s\S]*?<\/article>/g)].slice(0, 6).map(([card]) =>
  card.replace(/(<([\w]+)[^>]*\bdata-i18n="([^"]+)"[^>]*>)[^<]*(<\/\2>)/g,
    (_, open, tag, key, close) => open + copy[key] + close)
    .replace(/ loading="lazy"/g, '')
    .replace(/src="\/assets\/([^"]+)"/g, (_, file) => {
      const optimized = file.replace(/^(apps\/(?:wechat|chrome|explorer|figma))\.png$/, '$1.webp').replace(/^format-stack\.png$/, 'format-stack-small.webp');
      const ext = path.extname(optimized).slice(1);
      const mime = ext === 'svg' ? 'image/svg+xml' : `image/${ext}`;
      return `src="data:${mime};base64,${fs.readFileSync(path.join(root, 'assets', optimized)).toString('base64')}"`;
    })
);
const cards = makeCards(siteCopy.zh);
const englishCards = makeCards(englishCopy);
for (const localized of [cards, englishCards]) {
  if (localized.length !== 6 || localized.some(card => card.includes('undefined'))) throw new Error('Website card extraction failed');
}
const css = fs.readFileSync(path.join(root, 'styles.css'), 'utf8');
const cardCss = css.slice(css.indexOf('.vp-product-surface {'), css.indexOf('.vp-photo-preview {'));
fs.mkdirSync(path.resolve(__dirname, '../src/generated'), {recursive: true});
fs.writeFileSync(path.resolve(__dirname, '../src/generated/website.ts'), `// Generated by scripts/prepare-promo.cjs from the website.\nexport const cards = ${JSON.stringify(cards)};\nexport const englishCards = ${JSON.stringify(englishCards)};\nexport const cardCss = ${JSON.stringify(cardCss)};\n`);
for (const file of ['vpaste-tray.svg', 'vpaste-logo.webp', 'vpaste-logo-master.svg', 'format-stack.webp', 'product/settings-theme-zh.webp', 'product/settings-theme-en.webp', 'artwork/desktop-windows.webp']) {
  fs.copyFileSync(path.join(root, 'assets', file), path.join(out, path.basename(file)));
}
console.log('Prepared six website cards in Chinese and English, with local brand/product assets.');
