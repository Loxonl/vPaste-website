const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const directory = path.resolve(__dirname, '../design');
fs.mkdirSync(directory, {recursive: true});
const output = path.join(directory, 'variants.json');
// Persist seeds across rerenders. Each is exactly 141 bytes / 1128 bits.
const previous = fs.existsSync(output) ? JSON.parse(fs.readFileSync(output, 'utf8')) : null;
const seeds = previous?.variants.map(v => v.seed) ?? ['A', 'B', 'C'].map(() => {const bytes = crypto.randomBytes(141); bytes[0] |= 128; return bytes.toString('hex');});
const draw = (seed, key) => crypto.createHash('sha256').update(Buffer.from(seed, 'hex')).update(key).digest().readUInt32BE(0) / 2 ** 32;
const take = (pool, seed, key) => pool.splice(Math.floor(draw(seed, key) * pool.length), 1)[0];
const palettes = [
  {name: '电光白', background: '#f9fbff', surface: '#e7efff', accent: '#075be8', ink: '#123466'},
  {name: '暖杏白', background: '#fff9ee', surface: '#ffe8c5', accent: '#b44820', ink: '#462b20'},
  {name: '冰薄荷', background: '#f1fcf8', surface: '#d4f5e8', accent: '#08725d', ink: '#123f36'},
];
const layouts = ['precision', 'ribbon', 'spotlight'];
const music = [{style: 'pulse', bpm: 132, key: 38}, {style: 'breaks', bpm: 108, key: 42}, {style: 'electro', bpm: 150, key: 45}];
const topics = [
  ['intro', '剪贴捷径，一键即达', 4], ['shortcut', '快捷呼出，直接粘贴', 5],
  ['history', '每次复制，都清晰可见', 6], ['formatting', '保留原有格式', 4],
  ['categories', '分类、标签与收藏', 4], ['search', '记得一点，就能找到', 8],
  ['preview', '粘贴前先预览', 7], ['queue', '粘贴队列', 8], ['drag', '跨应用拖拽', 6],
  ['types', '每种内容，都看得清楚', 11], ['settings', '按你的习惯工作', 5],
  ['local', '记录留在本机', 5], ['closing', 'GPL-3.0 开源', 7],
];
const variants = seeds.map((seed, i) => {
  const palette = take(palettes, seed, 'palette');
  const layout = take(layouts, seed, 'layout');
  const audio = take(music, seed, 'music');
  const totalBeats = audio.bpm * 40 / 60;
  const weights = topics.map(([kind, , weight]) => weight * (.94 + draw(seed, 'duration:' + kind) * .12));
  const sum = weights.reduce((a, b) => a + b, 0);
  const desired = weights.map(w => w * totalBeats / sum);
  const beats = desired.map(Math.floor);
  [...beats.keys()].sort((a, b) => (desired[b] - beats[b]) - (desired[a] - beats[a])).slice(0, totalBeats - beats.reduce((a, b) => a + b, 0)).forEach(index => beats[index]++);
  let fromBeat = 0;
  const shots = topics.map(([kind, title], index) => {
    const endBeat = fromBeat + beats[index];
    const shot = {kind, title, fromBeat, beats: beats[index], from: Math.round(fromBeat * 60 / audio.bpm * 30), to: Math.round(endBeat * 60 / audio.bpm * 30), cameraBias: (draw(seed, 'camera:' + kind) - .5) * 38};
    fromBeat = endBeat;
    return shot;
  });
  return {id: ['A', 'B', 'C'][i], name: palette.name, seed, seedBits: 1128, palette, layout, music: {...audio, hatVariant: Math.floor(draw(seed, 'hat-pattern') * 4), bassVariant: Math.floor(draw(seed, 'bass-pattern') * 3)}, titleMotion: layout === 'precision' ? 'horizontal-reveal' : layout === 'ribbon' ? 'vertical-roll' : 'focus-reveal', transitionFrames: layout === 'precision' ? 7 : layout === 'ribbon' ? 12 : 10, shots};
});
fs.writeFileSync(output, JSON.stringify({seedPolicy: 'Independent 1128-bit seeds. SHA-256 domain-separated draws use all 141 bytes; style choices sampled without replacement. Native product appearance and interaction are excluded from randomization.', variants}, null, 2));
fs.mkdirSync(path.resolve(__dirname, '../src/generated'), {recursive: true});
fs.writeFileSync(path.resolve(__dirname, '../src/generated/variants.ts'), '// Generated by scripts/design-variants.cjs\nexport const variants = ' + JSON.stringify(variants) + ' as const;\n');
console.log(variants.map(v => ({id: v.id, palette: v.name, layout: v.layout, music: v.music.style, bpm: v.music.bpm, frames: v.shots.at(-1).to})));
